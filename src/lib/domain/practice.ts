import type { ContestPlayer } from "./types";

/**
 * PRACTICE MODE — illustrative credits so the full flow can be exercised on a real fixture before the
 * owner has entered their Dream11 contest data. These are NOT Dream11 credits. Teams built with them
 * are always labelled illustrative and can never reach "Ready".
 *
 *   credit = clamp(roundToHalf(6.5 + 4.5 · p), 6.5, 11),  p = percentile of the player's projected base points in the pool
 *
 * Stronger projections cost more, so the 100-credit cap forces real trade-offs (top-11 by projection does not fit).
 */
export const PRACTICE_LABEL = "Practice mode · illustrative credits generated by MatchLab (not from Dream11)";
export const PRACTICE_MIN = 6.5;
export const PRACTICE_MAX = 11;

export function illustrativeCredits(projections: { key: string; projected: number }[]): Map<string, number> {
  const sorted = [...projections].sort((a, b) => a.projected - b.projected || a.key.localeCompare(b.key));
  const out = new Map<string, number>();
  const n = sorted.length;
  sorted.forEach((p, i) => {
    const pct = n > 1 ? i / (n - 1) : 0.5;
    const raw = PRACTICE_MIN + (PRACTICE_MAX - PRACTICE_MIN) * pct;
    out.set(p.key, Math.min(PRACTICE_MAX, Math.max(PRACTICE_MIN, Math.round(raw * 2) / 2)));
  });
  return out;
}

/** Fills ONLY unknown credits; owner-entered credits are never overwritten. */
export function withIllustrativeCredits(players: ContestPlayer[], projected: Map<string, number>): { players: ContestPlayer[]; filled: string[] } {
  const unknown = players.filter((p) => p.credits === null);
  const credits = illustrativeCredits(unknown.map((p) => ({ key: p.key, projected: projected.get(p.key) ?? 0 })));
  const filled: string[] = [];
  return {
    players: players.map((p) => {
      if (p.credits !== null) return p;
      filled.push(p.key);
      return { ...p, credits: credits.get(p.key) ?? null };
    }),
    filled,
  };
}
